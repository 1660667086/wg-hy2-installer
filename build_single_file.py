#!/usr/bin/env python3
"""Build the self-contained, reproducible server installer from project files."""
import argparse
import base64
import binascii
import gzip
import io
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parent
FILES = (
    'menu.sh', 'server_single_install.sh', 'server_dual_install.sh',
    'server_landing_prepare.sh', 'server_relay_import.sh', 'one_click_install.sh',
    'wg_hy2_generate.py', 'wg_hy2_install.py', 'import_relay_token.py',
    'panel_install.sh', 'panel_cli.py', 'panel_backend.py', 'panel_server.py', 'panel/index.html',
)
MODE = 0o700
HEADER = '''#!/usr/bin/env bash
# Generated by build_single_file.py. Local project code is embedded below.
set -Eeuo pipefail
umask 077
for command in base64 tar gzip; do
    command -v "$command" >/dev/null 2>&1 || { echo "缺少必需工具：$command" >&2; exit 1; }
done
WG_HY2_BUNDLED_DIR=$(mktemp -d "${TMPDIR:-/tmp}/wg-hy2-bundle.XXXXXXXX")
export WG_HY2_BUNDLED_DIR
cleanup_bundle() { rm -rf -- "$WG_HY2_BUNDLED_DIR"; }
trap cleanup_bundle EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
chmod 700 "$WG_HY2_BUNDLED_DIR"
mkdir -m 700 "$WG_HY2_BUNDLED_DIR/panel"
base64 -d <<'WG_HY2_EMBEDDED_ARCHIVE' | gzip -d | tar -xf - -C "$WG_HY2_BUNDLED_DIR"
'''
FOOTER = '''
WG_HY2_EMBEDDED_ARCHIVE
bash "$WG_HY2_BUNDLED_DIR/menu.sh" "$@"
'''


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError('Bundled source changed: expected exactly one replacement target')
    return source.replace(old, new, 1)


def contents(name):
    source = (ROOT / name).read_text(encoding='utf-8')
    if name == 'menu.sh':
        start = """    if ! curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \\
        --output \"$tmp/$file\" \"$BASE_URL/$file\"; then
        rm -rf -- \"$tmp\"
        printf '下载失败，未运行安装脚本。\\n' >&3
        return 1
    fi
"""
        end = """    if ! cp -R -- \"$WG_HY2_BUNDLED_DIR\"/* \"$tmp/\"; then
        rm -rf -- \"$tmp\"
        printf '准备内置安装文件失败。\\n' >&3
        return 1
    fi
"""
        source = replace_once(source, start, end)
    elif name == 'server_dual_install.sh':
        start = """    curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \\
        --output \"$tmp/$name\" \"$RAW_BASE/$name\"
"""
        end = '    cp -- "$WG_HY2_BUNDLED_DIR/$name" "$tmp/$name"\n'
        source = replace_once(source, start, end)
    return source.encode('utf-8')


def archive():
    tar_data = io.BytesIO()
    with tarfile.open(fileobj=tar_data, mode='w', format=tarfile.USTAR_FORMAT) as tf:
        for name in FILES:
            data = contents(name)
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = MODE
            info.mtime = 0
            info.uid = info.gid = 0
            info.uname = info.gname = ''
            tf.addfile(info, io.BytesIO(data))
    return tar_data.getvalue()


def render(tar_bytes, level=9):
    encoded = base64.b64encode(gzip.compress(tar_bytes, compresslevel=level, mtime=0)).decode('ascii')
    payload = '\n'.join(encoded[i:i + 76] for i in range(0, len(encoded), 76))
    return HEADER + payload + FOOTER


def build():
    return render(archive())


def embedded_files(text):
    """Return [(name, mode, data)] embedded in an install.sh text, or None."""
    if not (text.startswith(HEADER) and text.endswith(FOOTER)):
        return None
    payload = text[len(HEADER):len(text) - len(FOOTER)]
    try:
        raw = gzip.decompress(base64.b64decode(''.join(payload.split()), validate=True))
        with tarfile.open(fileobj=io.BytesIO(raw), mode='r:') as tf:
            return [(m.name, m.mode, tf.extractfile(m).read()) for m in tf.getmembers() if m.isfile()]
    except (binascii.Error, OSError, EOFError, tarfile.TarError):
        return None


def is_current(text):
    """True when install.sh embeds exactly the current sources.

    The compressed bytes are deliberately not compared: zlib builds such as
    zlib-ng produce different (equally valid) output for the same input, which
    would make an exact comparison fail on some machines.
    """
    return embedded_files(text) == [(name, MODE, contents(name)) for name in FILES]


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if install.sh differs from the sources')
    args = parser.parse_args()
    output = ROOT / 'install.sh'
    if args.check:
        if not output.is_file() or not is_current(output.read_text(encoding='utf-8')):
            parser.error('install.sh is out of date; run python3 build_single_file.py')
    else:
        output.write_text(build(), encoding='utf-8')
        output.chmod(0o755)
